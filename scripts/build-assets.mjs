// Bundles /personas/*.yaml and /prompts/*.md into TypeScript modules so the
// Worker can use them without filesystem access. Run by `npm run assets`,
// which `dev` and `deploy` call automatically.

import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'src', 'generated');

async function readDirFiles(dir, ext) {
  let names = [];
  try {
    names = await readdir(path.join(root, dir));
  } catch {
    return [];
  }
  const files = names
    .filter((n) => n.toLowerCase().endsWith(ext))
    .filter((n) => !n.startsWith('_') && !n.startsWith('.'))
    .sort();
  const out = [];
  for (const name of files) {
    const content = await readFile(path.join(root, dir, name), 'utf8');
    out.push([name.replace(ext, ''), content]);
  }
  return out;
}

function asModule(comment, typeName, entries) {
  const body = entries
    .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
    .join('\n');
  return `// Generated by scripts/build-assets.mjs — do not edit by hand.\n${comment}\n\nexport const ${typeName}: Record<string, string> = {\n${body}\n};\n`;
}

async function main() {
  await mkdir(outDir, { recursive: true });

  const personas = await readDirFiles('personas', '.yaml');
  const prompts = await readDirFiles('prompts', '.md');
  const knowledge = await readDirFiles('knowledge/seeds', '.json');

  await writeFile(
    path.join(outDir, 'personas.ts'),
    asModule('// Source of truth: /personas/*.yaml', 'SEED_PERSONAS', personas),
    'utf8',
  );
  await writeFile(
    path.join(outDir, 'prompts.ts'),
    asModule('// Source of truth: /prompts/*.md', 'PROMPTS', prompts),
    'utf8',
  );
  await writeFile(
    path.join(outDir, 'knowledge.ts'),
    asModule('// Source of truth: /knowledge/seeds/*.json', 'SEED_KNOWLEDGE', knowledge),
    'utf8',
  );

  console.log(`bundled ${personas.length} persona(s), ${prompts.length} prompt(s), ${knowledge.length} knowledge seed(s)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
